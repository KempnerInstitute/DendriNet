#!/usr/bin/env python
"""Write a pip constraints file pinning the stack this interpreter provides.

The pinned set is the dependency closure of this checkout's ``pyproject.toml``
(the hard dependencies plus the requested extras), resolved from the packages
installed in the running interpreter. Install the same stack elsewhere with::

    pip install -e ".[test]" -c setup/constraints/<file>.txt

Usage::

    python setup/freeze_constraints.py --extras test lint gpu plotting \\
        --output setup/constraints/core-py310-torch2.9.1.txt
"""

from __future__ import annotations

import argparse
import platform
import subprocess
from datetime import date
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10
    import tomli as tomllib

ROOT = Path(__file__).resolve().parents[1]


def _applies(requirement: Requirement, extras: set[str]) -> bool:
    if requirement.marker is None:
        return True
    return any(requirement.marker.evaluate({"extra": extra}) for extra in extras)


def root_requirements(extras: list[str]) -> list[Requirement]:
    """The checkout's hard dependencies and those of ``extras``."""
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    optional = project.get("optional-dependencies", {})
    unknown = sorted(set(extras) - set(optional))
    if unknown:
        raise SystemExit(f"unknown extras: {unknown}")
    lines = list(project["dependencies"])
    for extra in extras:
        lines += [
            item for item in optional[extra] if not item.startswith(project["name"])
        ]
    return [Requirement(line) for line in lines]


def closure(requirements: list[Requirement]) -> tuple[dict[str, str], list[str]]:
    """Installed name -> version for ``requirements`` and their dependencies."""
    pinned: dict[str, str] = {}
    missing: list[str] = []
    stack = [(item, {""}) for item in requirements]
    while stack:
        requirement, extras = stack.pop()
        if not _applies(requirement, extras):
            continue
        try:
            distribution = metadata.distribution(requirement.name)
        except metadata.PackageNotFoundError:
            missing.append(str(requirement))
            continue
        name = canonicalize_name(distribution.metadata["Name"])
        requested = {""} | set(requirement.extras)
        if name in pinned and not requirement.extras:
            continue
        pinned[name] = distribution.version
        for line in distribution.requires or []:
            stack.append((Requirement(line), requested))
    return pinned, sorted(set(missing))


def _commit() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--extras", nargs="*", default=[])
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    pinned, missing = closure(root_requirements(args.extras))
    header = [
        f"# Generated by setup/freeze_constraints.py on {date.today().isoformat()}",
        f"# Python {platform.python_version()} on {platform.system()} {platform.machine()}",
        f"# library commit {_commit()}; extras: {', '.join(args.extras) or 'none'}",
    ]
    if missing:
        header.append(f"# not installed, so not pinned: {', '.join(missing)}")
    lines = [f"{name}=={version}" for name, version in sorted(pinned.items())]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(header + lines) + "\n")
    print(f"Wrote {len(lines)} pins to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
