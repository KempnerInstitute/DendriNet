def aggregate_results(cleaned_results):
    """Produce mean and std of metrics over seeds and samples"""

    arch_cols = [
        "ee_value", "ie_value", "ei_ratio", 
        "branch_factors", "use_shunting", "network_category"
    ]
    if "nparams" in cleaned_results.columns:
        arch_cols.append("nparams")

    noise_cols = [col for col in cleaned_results.columns if col.startswith("noise_")]

    exclude_cols = arch_cols + noise_cols + ["experiment", "task_id", "job_dir", "seed"]
    metric_cols = [col for col in cleaned_results.columns if col not in exclude_cols]

    noise_patterns = []
    for col in noise_cols:
        parts = col.split("_")
        noise_type = parts[1]
        metric = parts[2]
        noise_level = parts[-2]
        pattern = (noise_type, metric, noise_level)
        noise_patterns.append(pattern)

    noise_patterns = list(set(noise_patterns))

    results = []
    for _, group in cleaned_results.groupby(arch_cols):
        row = dict(zip(arch_cols, group[arch_cols].iloc[0]))

        for noise_type, metric, noise_level in noise_patterns:
            pattern_cols = [col for col in noise_cols if
                            f"noise_{noise_type}_{metric}_{noise_level}" in col]
            
            values = group[pattern_cols].values.flatten()
            row[f"noise_{noise_type}_{metric}_{noise_level}_mean"] = np.mean(values)
            row[f"noise_{noise_type}_{metric}_{noise_level}_std"] = np.std(values)

        for col in metric_cols:
            values = group[col].values
            row[f"{col}_mean"] = np.mean(values)
            row[f"{col}_std"] = np.std(values)

        results.append(row)
    
    agg_results = pd.DataFrame(results)

    new_metric_cols = []
    for col in metric_cols:
        new_metric_cols.append(f"{col}_mean")
        new_metric_cols.append(f"{col}_std")

    cols = arch_cols + new_metric_cols + sorted(
        [col for col in agg_results.columns if col not in arch_cols + new_metric_cols]
    )
    agg_results = agg_results[cols]
    
    return agg_results


def main():
    """Main function"""
    args = parse_args()
    exp_dir = args.folder

    # Set up output directory
    if args.output:
        output_dir = args.output
    else:
        output_dir = exp_dir

    # Step 2: Collect results from performance directories
    print("Collecting results from performance directories...", flush=True)
    results_df, missing_df = collect_results(exp_dir)

    if results_df.empty:
        print("No results found. Check if the experiment directory is correct.", flush=True)
        return
    
    # Clean and process the results data
    print("Processing results data...", flush=True)
    clean_results = clean_results_data(results_df)

    agg_results = aggregate_results(clean_results)

    # Step 3: Generate plots
    print("Generating plots...", flush=True)
    generate_plots(agg_results, output_dir, "ei_sweep")

    # Save results data
    plot_dir = os.path.join(output_dir, "plots")
    os.makedirs(plot_dir, exist_ok=True)
    clean_results.to_csv(
        os.path.join(plot_dir, "ei_sweep_clean_results.csv"), index=False
    )

    print(f"\nAnalysis complete. Plot files saved to {plot_dir}", flush=True)


