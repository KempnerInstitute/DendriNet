#!/usr/bin/env python
"""
analyze_ei_sweep.py
------------------
Generate plots from the results of an EI sweep experiment.

This script:
1. Takes a timestamp ID or folder path as input.
2. Analyzes results for different IE and EE parameter values, grouping by network configurations (EINet Shunting, EINet No Shunting, MLP).
3. Generates summary plots in the plots directory, including:
    - Heatmaps of performance metrics vs. E/I parameters (overall and per network category).
    - Line plots showing metric vs. IE (with up to 5 representative EE value lines) per network category.
    - Line plots showing metric vs. EE (with up to 5 representative IE value lines) per network category.
    - Line plots showing metric vs. E/I Ratio per network category.
4. Reports missing or unfinished runs.
5. Creates a `network_comparison_summary.txt` detailing generated comparison plots.

Note: General 3D surface plots and non-grouped scatter plots are no longer generated by default to improve clarity. Specific grouped scatter plots might still be present if relevant for network comparison.

Usage:
    python scripts/analyze_ei_sweep.py --timestamp 20250411144518
    python scripts/analyze_ei_sweep.py --folder /path/to/results/ei_20250411144518
    python scripts/analyze_ei_sweep.py --all     # Analyze all ei_ folders
"""

