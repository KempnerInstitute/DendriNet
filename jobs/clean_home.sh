#!/bin/bash
# Home-directory cleanup, 2026-08-12. Every path below was individually
# inspected before being listed (real dirs, not symlinks; nothing referenced
# by the live insight_3way jobs; nothing under Misc./, data/cifar, alexnet_fc6,
# or the campaign checkpoints on netscratch).
# Expected recovery: ~27 GB (home was 92G/95G = 97%).
set -uo pipefail
cd /n/home12/rwhalen/DendriNet

echo "== BEFORE =="; df -h /n/home12/rwhalen | tail -1

# --- 1) Closed FF-track raw run artifacts (~17.4G). Verdicts live in the
#        ledger + finalized/; these are the raw checkpoints/logs behind them.
rm -rf profilings/dendrinet_harness/ff_stress/learncheck \
       profilings/dendrinet_harness/ff_stress/realtrain \
       profilings/dendrinet_harness/ff_stress/closeout \
       profilings/dendrinet_harness/ff_stress/learn_overlay

# --- 2) 1M step-profiler rank traces (~4.6G). Findings banked in memory/ledger;
#        regenerable via DENDRINET_PROFILE_STEPS. Keeps the small .log files.
rm -f profilings/dendrinet_harness/step_profile/trace_rank0.json \
      profilings/dendrinet_harness/step_profile/trace_rank1.json \
      profilings/dendrinet_harness/step_profile/trace_rank2.json \
      profilings/dendrinet_harness/step_profile/trace_rank3.json

# --- 3) CIFAR download duplicates from today's runs (~1.6G). The canonical
#        copy stays at data/cifar/. insight_3way is symlinks -- NOT touched.
rm -f  outputs/datasets/cifar/cifar-10-python.tar.gz
rm -rf outputs/insight_showcase/baseline/datasets \
       outputs/insight_showcase/optimized/datasets
rm -rf "outputs/indexed_backends/feedforward_no_opt/ff_large_no_opt_20260811235440/results/config_0/datasets" \
       "outputs/indexed_backends/feedforward_optimized/ff_large_optimized_20260812024650/results/config_0/datasets" \
       "outputs/indexed_backends/feedforward_triton/ff_large_triton_20260812133633/results/config_0/datasets"

# --- 4) Showcase model checkpoints (~2.5G): epoch_10..50 weight snapshots of
#        the demo runs. The exhibit is timing + loss curves (kept); weights
#        of a CIFAR demo net are not worth 139MB x ~18.
find outputs/insight_showcase -type d -name standard_checkpoints \
     -exec rm -rf {} +

# --- 5) June test artifacts (~1.4G): timestamped generated run dirs under
#        tests/. Regenerated by running the tests.
rm -rf tests/outputs tests/results

# --- 6) Conda package cache (~1G): downloaded archives, safe to clear.
/n/home12/rwhalen/.conda/envs/dendritic_env/../../condabin/conda clean --all --yes 2>/dev/null \
  || conda clean --all --yes

echo "== AFTER =="; df -h /n/home12/rwhalen | tail -1
