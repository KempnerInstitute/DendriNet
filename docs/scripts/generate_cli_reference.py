#!/usr/bin/env python3
"""Write ``docs/cli_reference.rst`` from the ``--help`` output of every command.

The commands are the console scripts declared in ``[project.scripts]`` of
``pyproject.toml``. Run from the repository root with the package importable
(for example ``PYTHONPATH=src``)::

    python docs/scripts/generate_cli_reference.py          # rewrite the page
    python docs/scripts/generate_cli_reference.py --check  # fail if it is stale
"""

from __future__ import annotations

import argparse
import contextlib
import importlib
import io
import os
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10
    import tomli as tomllib

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs" / "cli_reference.rst"
HELP_WIDTH = "88"

GROUPS = (
    ("scripts.training.", "Training"),
    ("scripts.deployment.", "Compact checkpoints"),
    ("scripts.sweeps.", "Sweeps"),
    ("scripts.analysis.", "Analysis"),
    ("scripts.tools.", "Configuration tools"),
)

HEADER = """\
.. _cli-reference:

Command-line reference
======================

.. This page is generated by docs/scripts/generate_cli_reference.py from the
   argument parsers. Do not edit it by hand; rerun the script instead.

Installing the package installs the commands below (``[project.scripts]`` in
``pyproject.toml``). Each section reproduces the command's ``--help`` output.
The guides show how the commands fit together: :doc:`quickstart` and
:doc:`runs_and_outputs` for training, :doc:`distributed_training` for
several GPUs, :doc:`sweeps` for sweeps, :doc:`checkpoint_analysis` for
checkpoint analysis and the collectors, and :doc:`model_compression` for
compact checkpoints.
"""


def help_output(name: str, target: str) -> str:
    """Return the ``--help`` text of one console script."""
    module_name, function_name = target.split(":")
    module = importlib.import_module(module_name)
    stdout = io.StringIO()
    saved_argv = sys.argv
    sys.argv = [name, "--help"]
    try:
        with (
            contextlib.redirect_stdout(stdout),
            contextlib.redirect_stderr(io.StringIO()),
        ):
            try:
                getattr(module, function_name)()
            except SystemExit:
                pass
    finally:
        sys.argv = saved_argv
    text = stdout.getvalue()
    start = text.find("usage:")
    if start < 0:
        raise RuntimeError(f"{name} printed no usage text for --help")
    return text[start:].rstrip() + "\n"


def render(scripts: dict[str, str]) -> str:
    sections = [HEADER]
    for prefix, title in GROUPS:
        names = [name for name, target in scripts.items() if prefix in target]
        if not names:
            continue
        sections.append(f"{title}\n{'-' * len(title)}\n")
        for name in names:
            literal = f"``{name}``"
            body = "\n".join(
                f"   {line}" if line else ""
                for line in help_output(name, scripts[name]).splitlines()
            )
            sections.append(
                f"{literal}\n{'~' * len(literal)}\n\n"
                f"Entry point: ``{scripts[name]}``\n\n"
                f".. code-block:: text\n\n{body}\n"
            )
    grouped = {n for p, _ in GROUPS for n, t in scripts.items() if p in t}
    missing = sorted(set(scripts) - grouped)
    if missing:
        raise RuntimeError(f"commands outside the known groups: {missing}")
    return "\n".join(sections).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="Exit 1 if the page is out of date."
    )
    args = parser.parse_args()
    os.environ["COLUMNS"] = HELP_WIDTH
    scripts = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["scripts"]
    page = render(scripts)
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != page:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; rerun {__file__}")
            return 1
        return 0
    OUTPUT.write_text(page)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
