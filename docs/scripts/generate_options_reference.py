#!/usr/bin/env python3
"""Write ``docs/options_reference.rst`` from the typed configuration dataclasses.

Every section reachable from ``dendritic_modeling.config.Config`` is listed
with its options, their types and their defaults, and each section links the
guide that explains it. Run from the repository root with the package
importable (for example ``PYTHONPATH=src``)::

    python docs/scripts/generate_options_reference.py          # rewrite the page
    python docs/scripts/generate_options_reference.py --check  # fail if it is stale
"""

from __future__ import annotations

import argparse
import dataclasses
import sys
import typing
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs" / "options_reference.rst"

HEADER = """\
.. _options-reference:

Options reference
=================

.. This page is generated by docs/scripts/generate_options_reference.py from
   the configuration dataclasses. Do not edit it by hand; rerun the script.

This page lists every option of the typed configuration sections with its type
and its default value. Each section links the guide that explains its options;
start from :doc:`configuration_guide`. Unknown keys raise when a configuration
loads (:ref:`strict-loader`). Some effective defaults depend on other options,
for example on the core type; the guides describe those cases.

The payload blocks ``model.core.population_network`` and
``model.core.unified_ei`` are checked by their model builders and documented
with their families (:ref:`population-options`, :ref:`unified-ei`). Sections
that plugins provide are described in :ref:`plugin-config-sections`.
"""

# Longest matching prefix wins; the value is the reST link to the guide.
GUIDES = {
    "": ":doc:`configuration_guide`",
    "experiment": ":ref:`random-seeds` and :ref:`dataset-splits`",
    "experiment.checkpointing": ":ref:`run-outputs`",
    "data": ":doc:`datasets`",
    "model": ":doc:`network_architectures`",
    "model.encoder": ":ref:`encoder-decoder-types`",
    "model.decoder": ":ref:`encoder-decoder-types`",
    "model.core": ":ref:`core-types`",
    "model.core.affine_mlp": ":ref:`baseline-models`",
    "model.core.shared_projection_shunting": ":doc:`comparison_models`",
    "model.core.architecture": ":doc:`structured_ei_cores`",
    "model.core.connectivity": ":doc:`structured_ei_cores`",
    "model.core.connectivity.structured": ":ref:`structured-connectivity`",
    "model.core.transfer": ":ref:`transfer-layer`",
    "model.core.morphology": ":doc:`dendritic_neurons`",
    "model.core.sparsity": ":ref:`synapse-variants`",
    "model.core.reactivation": ":ref:`gate-initialization`",
    "model.core.blocklinear": ":doc:`synapses`",
    "model.core.implementation": ":doc:`structured_ei_cores`",
    "model.core.spatial": ":ref:`spatial-cores`",
    "training": ":doc:`training_strategies`",
    "training.main.strategies": ":ref:`training-strategies`",
    "training.main.strategies.multi_stage": ":ref:`multi-stage-training`",
    "training.main.learning_strategy_config": ":ref:`local-credit-assignment`",
    "training.main.regularization": ":ref:`regularization-pruning`",
    "training.main.pruning": ":ref:`regularization-pruning`",
    "training.main.common.param_groups": ":ref:`parameter-groups`",
    "analysis": ":ref:`analyzer-catalogue`",
    "analysis.runtime": ":ref:`analysis-runtime`",
    "outputs": ":ref:`run-outputs`",
    "distributed": ":doc:`distributed_training`",
}

# Slots that plugins fill; without a plugin they hold a disabled placeholder.
PLUGIN_SLOTS = frozenset(
    {
        "model.vision_replacement",
        "model.pretrained_replacement",
        "training.transformer_replacement",
        "training.vision_replacement",
    }
)
PLUGIN_LINK = ":ref:`plugin-config-sections`"
# Slots that hold a library section unless a plugin provides one.
LIBRARY_SLOTS = {"model.transformer_replacement": "TransformerReplacementConfig"}

# Sections that only exist so that configurations of optional extensions load
# while disabled; they have no options to document beyond ``enabled``.
SKIP = (
    "model.vision_replacement",
    "model.pretrained_replacement",
    "model.transformer_replacement",
    "training.vision_replacement",
    "training.transformer_replacement",
)


def guide(path: str) -> str:
    best = ""
    for prefix in GUIDES:
        if (path == prefix or path.startswith(prefix + ".")) and len(prefix) >= len(
            best
        ):
            best = prefix
    return GUIDES[best]


def label(path: str) -> str:
    return "options-" + (path.replace(".", "-").replace("_", "-") or "top-level")


def type_name(annotation) -> str:
    # Python 3.10 reports parameterized generics such as list[int] as instances
    # of type; only an unparameterized class is named by its __name__, so every
    # Python version renders list[int] and dict[str, Any] the same way.
    if isinstance(annotation, type) and not typing.get_args(annotation):
        return annotation.__name__
    text = str(annotation).replace("typing.", "")
    while "dendritic_modeling." in text:
        start = text.index("dendritic_modeling.")
        end = start
        while end < len(text) and (text[end].isalnum() or text[end] in "._"):
            end += 1
        text = text[:start] + text[start:end].rsplit(".", 1)[-1] + text[end:]
    return text.replace("NoneType", "None")


def nested_dataclasses(annotation) -> list[type]:
    found = []
    if isinstance(annotation, type) and dataclasses.is_dataclass(annotation):
        found.append(annotation)
    for argument in typing.get_args(annotation):
        found.extend(nested_dataclasses(argument))
    return found


def default_value(field: dataclasses.Field):
    if field.default is not dataclasses.MISSING:
        return field.default
    if field.default_factory is not dataclasses.MISSING:
        return field.default_factory()
    return dataclasses.MISSING


def literal(value) -> str:
    """Render a default as it is written in YAML."""
    if value is dataclasses.MISSING:
        return "required"
    if isinstance(value, tuple):
        value = list(value)
    try:
        text = yaml.safe_dump(value, default_flow_style=True, width=10**6).strip()
    except yaml.YAMLError:
        text = repr(value)
    if text.endswith("\n..."):
        text = text[: -len("\n...")]
    text = text.removesuffix("...").strip()
    if len(text) > 60:
        text = text[:57] + "..."
    return f"``{text}``"


def section(path: str, cls: type) -> tuple[list[str], list[tuple[str, type]]]:
    hints = typing.get_type_hints(cls)
    rows, children = [], []
    for field in dataclasses.fields(cls):
        annotation = hints.get(field.name, field.type)
        value = default_value(field)
        nested = nested_dataclasses(annotation)
        child_path = f"{path}.{field.name}" if path else field.name
        if child_path in PLUGIN_SLOTS:
            rows.append(
                (f"``{field.name}``", "plugin section", f"disabled; {PLUGIN_LINK}")
            )
            continue
        if child_path in LIBRARY_SLOTS:
            kind = f"``{LIBRARY_SLOTS[child_path]}`` or plugin section"
            rows.append((f"``{field.name}``", kind, f"disabled; {PLUGIN_LINK}"))
            continue
        if field.name == "extensions" and isinstance(value, dict):
            rows.append(
                (f"``{field.name}``", "plugin sections", f"``{{}}``; {PLUGIN_LINK}")
            )
            continue
        if nested and not child_path.startswith(SKIP):
            default = f":ref:`{child_path} <{label(child_path)}>`"
            if value is None:
                default = "``None``; " + default
            children.extend((child_path, child) for child in nested)
        elif nested:
            default = "disabled"
        elif isinstance(value, dict) and value:
            default = "mapping; keys below"
        else:
            default = literal(value)
        rows.append((f"``{field.name}``", f"``{type_name(annotation)}``", default))
        if isinstance(value, dict) and value and not nested:
            for key, item in value.items():
                kind = type(item).__name__ if item is not None else ""
                rows.append(
                    (
                        f"``{field.name}.{key}``",
                        f"``{kind}``" if kind else "",
                        literal(item),
                    )
                )
    lines = [
        f".. _{label(path)}:",
        "",
        f"``{path}``" if path else "Top level",
        "-" * (len(path) + 4 if path else len("Top level")),
        "",
        f"Explained in {guide(path)}. Class ``{cls.__module__}.{cls.__qualname__}``.",
        "",
    ]
    if not rows:
        return [*lines, "This section takes no options.", ""], children
    lines += [
        ".. list-table::",
        "   :header-rows: 1",
        "   :widths: 34 33 33",
        "",
        "   * - Option",
        "     - Type",
        "     - Default",
    ]
    for name, kind, default in rows:
        lines += [f"   * - {name}", f"     - {kind}".rstrip(), f"     - {default}"]
    return [*lines, ""], children


def render() -> str:
    from dendritic_modeling.config import Config

    out = [HEADER]
    queue: list[tuple[str, type]] = [("", Config)]
    seen: set[str] = set()
    while queue:
        path, cls = queue.pop(0)
        if path in seen or path.startswith(SKIP):
            continue
        seen.add(path)
        lines, children = section(path, cls)
        out.extend(lines)
        queue.extend(children)
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="Exit 1 if the page is out of date."
    )
    args = parser.parse_args()
    page = render()
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != page:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; rerun {__file__}")
            return 1
        return 0
    OUTPUT.write_text(page)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
