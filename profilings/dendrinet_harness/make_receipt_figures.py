"""Generate the before/after PyTorch-profiler 'receipt' figures for the talk.

Reads the fresh measurement artifacts (no numbers are hard-coded):
  fresh_eager/ops_*_loop_b512.txt    + fresh_eager/results_loop.json
  fresh_triton/ops_*_triton_b512.txt + fresh_triton/results_triton.json

Writes:
  fresh_figures/receipt_before.png
  fresh_figures/receipt_after.png

Run:  python profilings/dendrinet_harness/make_receipt_figures.py
"""

from __future__ import annotations

import glob
import json
import os
import re

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "fresh_figures")
os.makedirs(OUT, exist_ok=True)

GATHER = "#B3372E"
OTHER = "#B0B0AA"
TRITON = "#2B4C9B"
INK = "#1F1F1C"

PCT = re.compile(r"(\d+\.\d+)%")


def self_cuda_pct(ops_path: str, row_name: str) -> float:
    """Self CUDA % is the 3rd percentage token on a row (after Self CPU % and
    CPU total %); the Name column ends at the first 2+-space run, and must match
    exactly (startswith would confuse _TritonSparseGather / ...Backward)."""
    with open(ops_path) as fh:
        for line in fh:
            name = re.split(r"\s{2,}", line.strip())[0]
            if name == row_name:
                pcts = PCT.findall(line)
                if len(pcts) >= 3:
                    return float(pcts[2])
    raise KeyError(f"{row_name} not found in {ops_path}")


def whole_step(results_path: str, batch: int) -> dict:
    for row in json.load(open(results_path)):
        if row.get("batch") == batch:
            return {
                "step_ms": row["whole_step"]["step_ms_mean"],
                "peak_gb": row["peak_mem_mb"] / 1024.0,
            }
    raise KeyError(f"batch {batch} not in {results_path}")


def receipt(ax, rows, title):
    names = [r[0] for r in rows]
    vals = [r[1] for r in rows]
    colors = [GATHER if r[2] else OTHER for r in rows]
    hatches = ["///" if r[2] else "" for r in rows]
    y = range(len(rows))[::-1]
    bars = ax.barh(list(y), vals, height=0.62, color=colors, edgecolor="white")
    for b, h in zip(bars, hatches):
        b.set_hatch(h)
    for yi, v in zip(y, vals):
        ax.text(v + 1.0, yi, f"{v:.1f}%", va="center", fontsize=11,
                fontweight="bold", color=INK)
    ax.set_yticks(list(y))
    ax.set_yticklabels(names, fontsize=11)
    ax.set_xlim(0, 100)
    ax.set_xlabel("% of GPU time (Self CUDA)", fontsize=10)
    ax.set_title(title, fontsize=12, loc="left", color=INK)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.tick_params(length=0)
    ax.grid(axis="x", color="#EAEAE5", linewidth=0.8)
    ax.set_axisbelow(True)


def main() -> None:
    eager_ops = glob.glob(os.path.join(HERE, "fresh_eager", "ops_*_loop_b512.txt"))[0]
    triton_ops = glob.glob(os.path.join(HERE, "fresh_triton", "ops_*_triton_b512.txt"))[0]
    eag = whole_step(os.path.join(HERE, "fresh_eager", "results_loop.json"), 512)
    tri = whole_step(os.path.join(HERE, "fresh_triton", "results_triton.json"), 512)

    # ---------------- BEFORE ----------------
    bwd = self_cuda_pct(eager_ops, "aten::_index_put_impl_")
    fwd = self_cuda_pct(eager_ops, "aten::index")
    mul = self_cuda_pct(eager_ops, "aten::mul")
    ssum = self_cuda_pct(eager_ops, "aten::sum")
    rest = max(0.0, 100.0 - (bwd + fwd + mul + ssum))
    rows = [
        ("gather backward (scatter)\naten::_index_put_impl_", bwd, True),
        ("gather forward\naten::index", fwd, True),
        ("multiply  (aten::mul)", mul, False),
        ("sum  (aten::sum)", ssum, False),
        ("everything else", rest, False),
    ]
    fig, ax = plt.subplots(figsize=(10.5, 4.6))
    receipt(ax, rows, "Eager (loop) — sglimit5 wind tunnel, H100, batch 512")
    ax.annotate(f"gather = {bwd + fwd:.1f}% — zero FLOPs",
                xy=(56, 3.5), fontsize=13, fontweight="bold", color=GATHER)
    fig.text(0.07, 0.015,
             f"whole step {eag['step_ms']:,.0f} ms  ·  peak memory "
             f"{eag['peak_gb']:.1f} GB of 80 GB  ·  "
             "generated by make_receipt_figures.py from ops_*_loop_b512.txt",
             fontsize=8.5, color="#6E6E67")
    fig.tight_layout(rect=(0, 0.05, 1, 1))
    fig.savefig(os.path.join(OUT, "receipt_before.png"), dpi=200)

    # ---------------- AFTER ----------------
    tbwd = self_cuda_pct(triton_ops, "_TritonSparseGatherBackward")
    tfwd = self_cuda_pct(triton_ops, "_TritonSparseGather")
    tcpy = self_cuda_pct(triton_ops, "aten::copy_")
    tmul = self_cuda_pct(triton_ops, "aten::mul")
    trest = max(0.0, 100.0 - (tbwd + tfwd + tcpy + tmul))
    rows = [
        ("gather backward\n_sparse_gather_gx_t + _gw_t", tbwd, True),
        ("gather forward\n_sparse_gather_fwd_t", tfwd, True),
        ("copies  (aten::copy_)", tcpy, False),
        ("multiply  (aten::mul)", tmul, False),
        ("everything else", trest, False),
    ]
    fig, (ax, ax2) = plt.subplots(
        2, 1, figsize=(10.5, 6.0), height_ratios=(3.2, 1.0))
    receipt(ax, rows, "Triton v3 — same instrument, same config, same GPU")
    ax.annotate(f"still the biggest: {tbwd + tfwd:.1f}% — no second hero",
                xy=(38, 3.5), fontsize=12, fontweight="bold", color=GATHER)

    # absolute scale: the pie itself shrank
    ax2.barh([1], [eag["step_ms"]], height=0.55, color=OTHER)
    ax2.barh([0], [tri["step_ms"]], height=0.55, color=TRITON)
    ax2.text(eag["step_ms"] + 30, 1, f"eager  {eag['step_ms']:,.0f} ms",
             va="center", fontsize=11, color=INK)
    ax2.text(tri["step_ms"] + 30, 0,
             f"Triton v3  {tri['step_ms']:,.0f} ms  "
             f"({eag['step_ms'] / tri['step_ms']:.1f}x)",
             va="center", fontsize=11, fontweight="bold", color=TRITON)
    ax2.set_yticks([])
    ax2.set_xlim(0, eag["step_ms"] * 1.35)
    ax2.set_xlabel("whole step, drawn to scale (ms)", fontsize=10)
    ax2.set_title("…but it is a share of a pie that shrank:", fontsize=11,
                  loc="left", color=INK)
    for s in ("top", "right", "left"):
        ax2.spines[s].set_visible(False)
    ax2.tick_params(length=0)
    fig.text(0.07, 0.012,
             f"peak memory {eag['peak_gb']:.1f} → {tri['peak_gb']:.1f} GB  ·  "
             "generated by make_receipt_figures.py from ops_*_triton_b512.txt",
             fontsize=8.5, color="#6E6E67")
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(os.path.join(OUT, "receipt_after.png"), dpi=200)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
